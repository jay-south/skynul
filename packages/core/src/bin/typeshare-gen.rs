use std::env;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

fn main() -> ExitCode {
    let core_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let root = core_dir
        .parent()
        .and_then(|p| p.parent())
        .expect("repo root");
    let input = core_dir.join("src/api");
    let output = root.join("src/shared/generated.ts");

    if !ensure_typeshare() {
        eprintln!("typeshare-gen: failed to install typeshare-cli");
        return ExitCode::FAILURE;
    }

    let status = Command::new("typeshare")
        .arg(input)
        .arg("--lang=typescript")
        .arg(format!("--output-file={}", output.display()))
        .status();

    match status {
        Ok(s) if s.success() => {
            prepend_header(&output);
            println!("typeshare-gen: wrote {}", output.display());
            ExitCode::SUCCESS
        }
        Ok(s) => {
            eprintln!("typeshare-gen: exited with {s}");
            ExitCode::from(s.code().unwrap_or(1) as u8)
        }
        Err(e) => {
            eprintln!("typeshare-gen: {e}");
            ExitCode::FAILURE
        }
    }
}

fn ensure_typeshare() -> bool {
    if Command::new("typeshare")
        .arg("--version")
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false)
    {
        return true;
    }

    eprintln!("typeshare-gen: installing typeshare-cli...");
    Command::new("cargo")
        .args(["install", "typeshare-cli", "--locked", "--quiet"])
        .status()
        .map(|s| s.success())
        .unwrap_or(false)
}

fn prepend_header(path: &Path) {
    let body = std::fs::read_to_string(path).unwrap_or_default();
    let header = "// @generated by `pnpm gen:types` — do not edit manually\n\n";
    if body.starts_with("// @generated") {
        return;
    }
    std::fs::write(path, format!("{header}{body}")).ok();
}
